import { dirname } from "node:path";

/** XML-escape a plist string value (paths may legally contain & < > ' "). */
function xml(value: string): string {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");
}

/** systemd-quote one ExecStart argument (double quotes + backslash escapes). */
function sdQuote(value: string): string {
  return `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

/**
 * Unit fields are persisted into supervisor definitions — newlines or other
 * control characters would inject directives (sage R-111 security finding).
 * Reject them outright; no legitimate path on either platform carries them.
 */
export function validateUnitContext(ctx: UnitContext): void {
  for (const [field, value] of Object.entries(ctx)) {
    if (value !== undefined && /[\n\r\0]/.test(value)) {
      throw new Error(`unit field ${field} contains control characters — refusing to render`);
    }
  }
}

/** Everything a unit needs — resolved by the caller, pure here (FR-7). */
export interface UnitContext {
  /** launchd label / systemd unit name stem. */
  label: string;
  bunPath: string;
  daemonScript: string;
  workingDir: string;
  home: string;
  logsDir: string;
  /** Absolute config path → `REFLEX_CONFIG` in the unit env (named
   * instances, reflex#37). Unset: no entry, the default render. */
  reflexConfig?: string;
}

export const SERVICE_LABEL = "ai.meta-factory.reflex";

const HEADER_COMMENT =
  "generated by `reflex service install` — re-rendered on every install; manual edits are overwritten";

/** macOS LaunchAgent (the cortex/sage ecosystem pattern): RunAtLoad + KeepAlive. */
export function renderLaunchdPlist(ctx: UnitContext): string {
  validateUnitContext(ctx);
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- ${HEADER_COMMENT} -->
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>${xml(ctx.label)}</string>
    <key>ProgramArguments</key>
    <array>
        <string>${xml(ctx.bunPath)}</string>
        <string>${xml(ctx.daemonScript)}</string>
    </array>
    <key>WorkingDirectory</key>
    <string>${xml(ctx.workingDir)}</string>
    <key>RunAtLoad</key>
    <true/>
    <key>KeepAlive</key>
    <true/>
    <key>StandardOutPath</key>
    <string>${xml(ctx.logsDir)}/reflex.log</string>
    <key>StandardErrorPath</key>
    <string>${xml(ctx.logsDir)}/reflex.error.log</string>
    <key>EnvironmentVariables</key>
    <dict>
        <key>HOME</key>
        <string>${xml(ctx.home)}</string>
        <key>PATH</key>
        <string>${xml(dirname(ctx.bunPath))}:/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin</string>${
          ctx.reflexConfig === undefined
            ? ""
            : `
        <key>REFLEX_CONFIG</key>
        <string>${xml(ctx.reflexConfig)}</string>`
        }
    </dict>
</dict>
</plist>
`;
}

/** Linux user unit: Restart=always, journal-logged. */
export function renderSystemdUnit(ctx: UnitContext): string {
  validateUnitContext(ctx);
  return `# ${HEADER_COMMENT}
[Unit]
Description=Reflex — metafactory activation runtime
After=network.target

[Service]
ExecStart=${sdQuote(ctx.bunPath)} ${sdQuote(ctx.daemonScript)}
WorkingDirectory=${sdQuote(ctx.workingDir)}
Restart=always
RestartSec=2
Environment=${sdQuote(`HOME=${ctx.home}`)}
${ctx.reflexConfig === undefined ? "" : `Environment=${sdQuote(`REFLEX_CONFIG=${ctx.reflexConfig}`)}\n`}
[Install]
WantedBy=default.target
`;
}
