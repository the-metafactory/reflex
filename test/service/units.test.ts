import { describe, expect, it } from "bun:test";
import { renderLaunchdPlist, renderSystemdUnit, SERVICE_LABEL } from "../../src/service/units";

const ctx = {
  label: SERVICE_LABEL,
  bunPath: "/opt/bun/bin/bun",
  daemonScript: "/repo/src/bin/reflex-daemon.ts",
  workingDir: "/repo",
  home: "/home/op",
  logsDir: "/home/op/.config/reflex/logs",
};

describe("renderLaunchdPlist", () => {
  const plist = renderLaunchdPlist(ctx);
  it("carries label, absolute program arguments, logs, KeepAlive, env", () => {
    expect(plist).toContain("<string>ai.meta-factory.reflex</string>");
    expect(plist).toContain("<string>/opt/bun/bin/bun</string>");
    expect(plist).toContain("<string>/repo/src/bin/reflex-daemon.ts</string>");
    expect(plist).toContain("<string>/repo</string>");
    expect(plist).toContain("<string>/home/op/.config/reflex/logs/reflex.log</string>");
    expect(plist).toContain("<string>/home/op/.config/reflex/logs/reflex.error.log</string>");
    expect(plist).toContain("<key>KeepAlive</key>\n    <true/>");
    expect(plist).toContain("<key>RunAtLoad</key>\n    <true/>");
    expect(plist).toContain("<string>/opt/bun/bin:/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin</string>");
  });
  it("carries the generated-by header", () => {
    expect(plist).toContain("generated by `reflex service install`");
  });
});

describe("renderSystemdUnit", () => {
  const unit = renderSystemdUnit(ctx);
  it("carries ExecStart, Restart=always, WantedBy and header", () => {
    expect(unit).toContain('ExecStart="/opt/bun/bin/bun" "/repo/src/bin/reflex-daemon.ts"');
    expect(unit).toContain("Restart=always");
    expect(unit).toContain("RestartSec=2");
    expect(unit).toContain('WorkingDirectory="/repo"');
    expect(unit).toContain("WantedBy=default.target");
    expect(unit).toContain("generated by `reflex service install`");
  });
});

describe("escaping + injection rejection (sage R-111)", () => {
  it("XML-escapes plist values (& and < in paths)", () => {
    const plist = renderLaunchdPlist({ ...ctx, workingDir: "/repo/a&b<c" });
    expect(plist).toContain("<string>/repo/a&amp;b&lt;c</string>");
    expect(plist).not.toContain("a&b<c</string>");
  });
  it("quotes systemd paths with whitespace", () => {
    const unit = renderSystemdUnit({ ...ctx, workingDir: "/repo with space" });
    expect(unit).toContain('WorkingDirectory="/repo with space"');
  });
  it("rejects control characters in any unit field", () => {
    expect(() => renderSystemdUnit({ ...ctx, home: "/home/op\nExecStart=/bin/evil" })).toThrow(/control characters/);
    expect(() => renderLaunchdPlist({ ...ctx, bunPath: "/bin/bun\r" })).toThrow(/control characters/);
  });
});
